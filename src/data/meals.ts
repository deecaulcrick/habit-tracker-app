/** Pick one idea per slot (Nigerian first) whose total lands closest to the calorie target. */
export function buildDayPlan(target: number, seed: number): MealIdea[] {
  const pool = MEAL_IDEAS.filter((m) => m.ng);
  const bySlot = (s: MealSlot) => pool.filter((m) => m.slot === s);
  const combos: MealIdea[][] = [];
  for (const x of bySlot('breakfast'))
    for (const y of bySlot('lunch'))
      for (const z of bySlot('dinner')) for (const w of bySlot('snack')) combos.push([x, y, z, w]);
  const scored = combos
    .map((c) => ({ c, diff: Math.abs(target - c.reduce((n, m) => n + m.kcal, 0)) }))
    .sort((p, q) => p.diff - q.diff)
    .slice(0, 15);
  return scored[Math.abs(seed) % scored.length].c;
}
