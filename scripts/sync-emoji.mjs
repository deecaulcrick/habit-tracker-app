#!/usr/bin/env node
/**
 * Bundles the Fluent 3D emoji the app actually uses.
 *
 * Scans src/ for emoji characters, copies each matching image from
 * @lobehub/fluent-emoji-3d into assets/emoji/, and writes
 * src/constants/emoji-assets.ts so <Emo> can render them as images.
 *
 * Run after adding new emoji: `npm run emoji`
 */
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const srcDir = path.join(root, 'src');
const pkgDir = path.join(root, 'node_modules/@lobehub/fluent-emoji-3d/assets');
const outDir = path.join(root, 'assets/emoji');
const mapFile = path.join(srcDir, 'constants/emoji-assets.ts');

const EMOJI_RE = /\p{Extended_Pictographic}(?:️|‍\p{Extended_Pictographic}|\p{Emoji_Modifier})*/gu;
const strip = (s) => s.replace(/️/g, '');
const hex = (s) => [...s].map((c) => c.codePointAt(0).toString(16)).join('-');

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const p = path.join(dir, d.name);
    if (d.isDirectory()) return walk(p);
    return /\.(ts|tsx)$/.test(d.name) && p !== mapFile ? [p] : [];
  });
}

const found = new Set();
for (const file of walk(srcDir)) {
  for (const m of fs.readFileSync(file, 'utf8').matchAll(EMOJI_RE)) found.add(strip(m[0]));
}

fs.mkdirSync(outDir, { recursive: true });
for (const f of fs.readdirSync(outDir)) fs.unlinkSync(path.join(outDir, f));

const entries = [];
const missing = [];
for (const glyph of [...found].sort()) {
  const bare = hex(glyph);
  const withVs = hex(glyph.length <= 2 ? glyph + '️' : glyph);
  const candidates = [bare, withVs, hex(glyph + '\uFE0F'), hex([...glyph].join('\uFE0F'))];
  const hit = candidates.find((c) => fs.existsSync(path.join(pkgDir, `${c}.webp`)));
  if (!hit) {
    missing.push(glyph);
    continue;
  }
  fs.copyFileSync(path.join(pkgDir, `${hit}.webp`), path.join(outDir, `${bare}.webp`));
  entries.push(`  '${glyph}': require('@/assets/emoji/${bare}.webp'),`);
}

fs.writeFileSync(
  mapFile,
  `// Generated by scripts/sync-emoji.mjs — do not edit by hand.\n` +
    `// Fluent Emoji 3D © Microsoft, MIT licence (via @lobehub/fluent-emoji-3d).\n\n` +
    `export const EMOJI_ASSETS: Record<string, number> = {\n${entries.join('\n')}\n};\n`
);

console.log(`Bundled ${entries.length} emoji into assets/emoji/`);
if (missing.length) console.log(`No 3D art for: ${missing.join(' ')} (falls back to text)`);
